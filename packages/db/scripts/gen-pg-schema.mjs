// Derives prisma/postgres/schema.prisma (Neon, AD034/AD037) from the SQLite-compatible prisma/schema.prisma.
// Run: pnpm --filter @agentmeter/db schema:pg   (also run by generate:pg). Never edit the output by hand.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "prisma");
const src = readFileSync(join(root, "schema.prisma"), "utf8").replace(/\r\n/g, "\n");
if (!src.includes('provider = "sqlite"')) throw new Error("source schema is not the sqlite variant");

const out = src
  .replace('provider = "sqlite"', 'provider  = "postgresql"')
  .replace('url      = env("DATABASE_URL")', 'url       = env("DATABASE_URL") // Neon POOLED string (host has -pooler)\n  directUrl = env("DIRECT_URL") // Neon DIRECT string, used by prisma migrate only')
  .replace(/^\/\/ AgentMeter persistence[\s\S]*?\n\n/, "// GENERATED by scripts/gen-pg-schema.mjs from ../schema.prisma. Do not edit.\n\n");

mkdirSync(join(root, "postgres"), { recursive: true });
writeFileSync(join(root, "postgres", "schema.prisma"), out);
console.log("wrote prisma/postgres/schema.prisma");
